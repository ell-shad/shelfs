export type MessageKey = keyof typeof strings;

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  let out: string = strings[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function pluralBooks(n: number): string {
  return n === 1 ? t("oneBook") : t("allBooks", { n });
}

/** A user-facing message for any thrown API or parsing error. */
export function apiErrorMessage(error: unknown): string {
  if (error instanceof Error) return error.message;
  return String(error);
}
